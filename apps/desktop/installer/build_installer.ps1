param(
    [switch]$RebuildPayload
)
$ErrorActionPreference = 'Stop'
$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$rootDir = Split-Path -Parent $scriptDir
Set-Location $rootDir

$wpfDir = 'C:\Windows\Microsoft.NET\Framework64\v4.0.30319\WPF'
$netDir = 'C:\Windows\Microsoft.NET\Framework64\v4.0.30319'
$icoPath = "$rootDir\app.ico"

# 1. Read package.json and release.json
$pkg = Get-Content "$rootDir\package.json" -Raw -Encoding UTF8 | ConvertFrom-Json
$version = $pkg.version
$release = Get-Content "$scriptDir\release.json" -Raw -Encoding UTF8 | ConvertFrom-Json

$manifestUrl = "https://firebasestorage.googleapis.com/v0/b/judge-remote-mcp-2026.firebasestorage.app/o/judge-desktop%2Flatest%2Flatest.json?alt=media"
$manifestFallbackUrl = "https://github.com/$($release.githubRepo)/releases/latest/download/latest.json"
$installerUrl = "https://github.com/$($release.githubRepo)/releases/download/v$version/$($release.installerFileName)"

function CsStr([string]$s) { return '"' + ($s -replace '\\', '\\' -replace '"', '\"') + '"' }

$buildInfo = @"
// Auto-generated by build_installer.ps1
namespace JudgeResearch {
    internal static class BuildInfo {
        public const string Version = $(CsStr $version);
        public const string ManifestUrl = $(CsStr $manifestUrl);
        public const string ManifestFallbackUrl = $(CsStr $manifestFallbackUrl);
    }
}
"@
[IO.File]::WriteAllText("$scriptDir\BuildInfo.g.cs", $buildInfo, (New-Object Text.UTF8Encoding($false)))
Write-Host "Target Version: $version / Manifest: $manifestUrl"

# 2. Package win-unpacked payload if requested or if missing
$unpacked = "$rootDir\release\win-unpacked"
if (($RebuildPayload -or !(Test-Path "$scriptDir\app-payload.zip")) -and (Test-Path $unpacked)) {
    Write-Host "Creating app-payload.zip from $unpacked..."
    Remove-Item "$scriptDir\app-payload.zip" -Force -ErrorAction SilentlyContinue
    Add-Type -AssemblyName System.IO.Compression.FileSystem
    [IO.Compression.ZipFile]::CreateFromDirectory($unpacked, "$scriptDir\app-payload.zip", [IO.Compression.CompressionLevel]::Optimal, $false)
}

if (!(Test-Path "$scriptDir\app-payload.zip")) {
    throw "app-payload.zip not found! Cannot compile complete installer without payload. Run electron-builder or build win-unpacked first."
}

# 3. References for csc.exe
$refs = @(
    "$wpfDir\PresentationFramework.dll",
    "$wpfDir\PresentationCore.dll",
    "$wpfDir\WindowsBase.dll",
    "$netDir\System.dll",
    "$netDir\System.Core.dll",
    "$netDir\System.Xaml.dll",
    "$netDir\System.Windows.Forms.dll",
    "$netDir\System.Drawing.dll",
    "$netDir\System.IO.Compression.dll",
    "$netDir\System.IO.Compression.FileSystem.dll",
    "$netDir\System.Web.Extensions.dll",
    "$netDir\Microsoft.CSharp.dll"
)
$refArgs = $refs | ForEach-Object { "/r:`"$_`"" }
$common = @("$scriptDir\UpdateCommon.cs", "$scriptDir\UpdateModels.cs", "$scriptDir\BuildInfo.g.cs")

function Compile($out, $sources, $extra) {
    Write-Host "Compiling $out..."
    & "$netDir\csc.exe" /nologo /target:winexe /optimize+ /platform:anycpu /utf8output /codepage:65001 /win32icon:"$icoPath" $refArgs /resource:"$icoPath",app.ico $extra /out:"$out" $sources
    if ($LASTEXITCODE -ne 0) { throw "Compile failed for $out" }
}

# 4. Compile Uninstaller
$uninstallerSources = @("$scriptDir\UninstallerApp.cs", "$scriptDir\UninstallerWindow.Logic.cs", "$scriptDir\UninstallerWindow.UI.Cards.cs", "$scriptDir\UninstallerWindow.UI.Frame.cs", "$scriptDir\UninstallerWindow.UI.Helpers.cs", "$scriptDir\UninstallerEntry.cs")
Compile "$scriptDir\uninstall.exe" ($uninstallerSources + $common) @()

# 5. Compile Updater
$updaterSources = @("$scriptDir\UpdaterApp.cs", "$scriptDir\UpdaterWindow.UI.cs", "$scriptDir\UpdaterWindow.Render.cs", "$scriptDir\UpdaterWindow.Download.cs", "$scriptDir\UpdaterWindow.Helpers.cs", "$scriptDir\UpdaterEntry.cs")
Compile "$scriptDir\JudgeResearchUpdater.exe" ($updaterSources + $common) @()

# 6. Compile Setup Installer with embedded resources
$resList = @()
if (Test-Path "$scriptDir\app-payload.zip") {
    $resList += "/resource:`"$scriptDir\app-payload.zip`",app-payload.zip"
}
$resList += "/resource:`"$scriptDir\uninstall.exe`",uninstall.exe"
$resList += "/resource:`"$scriptDir\JudgeResearchUpdater.exe`",JudgeResearchUpdater.exe"

$installerOut = "$rootDir\$($release.installerFileName)"
$installerSources = @("$scriptDir\InstallerApp.cs", "$scriptDir\InstallerWindow.Setup.cs", "$scriptDir\InstallerWindow.UI.Frame.cs", "$scriptDir\InstallerWindow.UI.Cards.cs", "$scriptDir\InstallerWindow.UI.Helpers.cs", "$scriptDir\InstallerWindow.Install.cs", "$scriptDir\InstallerWindow.Shell.cs", "$scriptDir\InstallerEntry.cs")
Compile $installerOut ($installerSources + $common) $resList
Copy-Item $installerOut "$scriptDir\$($release.installerFileName)" -Force

# 7. Generate publish manifest (latest.json)
$publishDir = "$scriptDir\publish"
New-Item -ItemType Directory -Force $publishDir | Out-Null
$publishExe = Join-Path $publishDir $release.installerFileName
Copy-Item $installerOut $publishExe -Force

$file = Get-Item $publishExe
$sha = (Get-FileHash $publishExe -Algorithm SHA256).Hash.ToLower()

$manifest = [ordered]@{
    version        = $version
    minimumVersion = $release.minimumVersion
    mandatory      = [bool]$release.mandatory
    releaseDate    = (Get-Date -Format 'yyyy-MM-dd')
    installerUrl   = $installerUrl
    size           = $file.Length
    sha256         = $sha
    notes          = $release.notes
}

$manifestJson = $manifest | ConvertTo-Json -Depth 5
[IO.File]::WriteAllText("$publishDir\latest.json", $manifestJson, (New-Object Text.UTF8Encoding($false)))

Write-Host "=== Build Completed Successfully ==="
Write-Host "Installer: $installerOut"
Write-Host "Publish Dir: $publishDir (includes latest.json and installer)"
